package org.openprovenance.bench.throughput;

import java.io.File;
import java.lang.management.ManagementFactory;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

/**
 * The direct JDBC mode's commands, as the Makefile calls them ({@code -Pdirect} build, the generated webapp's classes
 * and libraries on the classpath): {@code java ... DirectMain <command> [KEY=value ...]}.
 *
 * <pre>
 *   direct-run      one run: FAMILY LAYER KEY READBACK HASH RELATIONS N B JDBC_BATCH WARMUP DURATION [WRITERS QUEUE BATCH]
 *   direct-plan     the plan and its budget, nothing run
 *   direct-matrix   the plan (PLAN=full|smoke), results/&lt;date&gt;-direct[-LABEL].csv/.md
 *   direct-compare  direct against HTTP from the results files (results/&lt;date&gt;-direct[-LABEL]-compare.md)
 * </pre>
 *
 * <p>This JVM loads the service's classes (service-templates-core) in-process, and they read TPL_*, PROV_*,
 * TEMPLATE_CONFIG, JDBC_POOL_SIZE from the environment as they would in the service: when any is set, the command is
 * run again in a JVM of its own without them, so nothing of the caller's environment (the deployed stores'
 * credentials, a template configuration) reaches them. The guard refuses as in the HTTP mode (exit status 3).</p>
 */
public final class DirectMain {

    static final String INTRO = "Generated by `make bench.direct.matrix` / `make bench.direct.run` (modules-misc/benchmarks/service-throughput, "
            + "direct JDBC mode: no web service); see BENCHMARK.md, section \"Direct JDBC mode\".";

    public static void main(String[] args) throws Exception {
        if (args.length == 0) {
            System.err.println("usage: DirectMain direct-run|direct-plan|direct-matrix|direct-compare [KEY=value ...]");
            System.exit(2);
        }
        if (needsCleanEnvironment(System.getenv())) {
            System.exit(reexec(args));
        }
        Settings s = new Settings(Arrays.copyOfRange(args, 1, args.length));
        try {
            System.exit(command(args[0], s));
        } catch (Guard.Refused e) {
            System.err.println(e.getMessage());
            System.exit(3);
        }
    }

    /** Whether the environment carries a variable the service's classes would read (they must see none of the caller's). */
    static boolean needsCleanEnvironment(Map<String, String> env) {
        for (String k : env.keySet()) {
            if (isServiceVariable(k)) return true;
        }
        return false;
    }

    static boolean isServiceVariable(String k) {
        return k.startsWith("TPL_") || k.startsWith("PROV_") || k.startsWith("XPLAIN_") || k.equals("TEMPLATE_CONFIG") || k.equals("JDBC_POOL_SIZE");
    }

    private static int reexec(String[] args) throws Exception {
        List<String> cmd = new ArrayList<>();
        cmd.add(System.getProperty("java.home") + File.separator + "bin" + File.separator + "java");
        cmd.addAll(ManagementFactory.getRuntimeMXBean().getInputArguments());
        cmd.add("-cp");
        cmd.add(System.getProperty("java.class.path"));
        cmd.add(DirectMain.class.getName());
        cmd.addAll(Arrays.asList(args));
        ProcessBuilder pb = new ProcessBuilder(cmd).inheritIO();
        pb.environment().keySet().removeIf(DirectMain::isServiceVariable);
        return pb.start().waitFor();
    }

    static int command(String command, Settings s) throws Exception {
        switch (command) {
            case "direct-run": {
                Report report = new Report(s, "direct");
                new Store(s).guard();
                recordEnvironment(report);
                Run.Row row = new DirectRun(s).execute("d" + System.currentTimeMillis() / 1000);
                appendAligned(report, row);
                report.writeMarkdown("Service throughput, direct JDBC mode, " + report.name, null, DirectMatrix.COLUMNS, INTRO, DirectMatrix.LEGEND);
                System.out.println("results: " + report.csv() + ", " + report.markdown());
                return row.ok() ? 0 : 1;
            }
            case "direct-plan":
                System.out.println(DirectMatrix.describe(DirectMatrix.plan(s), s));
                return 0;
            case "direct-matrix":
                return DirectMatrix.run(s);
            case "direct-compare":
                return Compare.run(s);
            default:
                throw new IllegalArgumentException("unknown command " + command);
        }
    }

    /** The environment file of a direct report: the HTTP mode's, and this client JVM in place of the service's. */
    static void recordEnvironment(Report report) throws Exception {
        report.recordEnvironment();
        File f = report.environment();
        String text = java.nio.file.Files.readString(f.toPath());
        if (!text.contains("| direct client JVM |")) {
            text = text + "| direct client JVM | " + System.getProperty("java.vendor") + " " + System.getProperty("java.version") + "; "
                    + String.join(" ", ownJvmArguments()).replace("|", "\\|")
                    + "; the service JVM rows above do not apply (no service) |\n";
            java.nio.file.Files.writeString(f.toPath(), text);
        }
    }

    /** This JVM's arguments, without those JAVA_TOOL_OPTIONS added (the machine's, not the benchmark's). */
    static List<String> ownJvmArguments() {
        String tool = System.getenv("JAVA_TOOL_OPTIONS");
        List<String> fromTool = tool == null ? List.of() : Arrays.asList(tool.trim().split("\\s+"));
        List<String> own = new ArrayList<>();
        for (String a : ManagementFactory.getRuntimeMXBean().getInputArguments()) {
            if (!fromTool.contains(a)) own.add(a);
        }
        return own;
    }

    /** A row padded to the CSV's header (an aborted run carries fewer columns). */
    static void appendAligned(Report report, Run.Row row) throws java.io.IOException {
        List<Map<String, String>> existing = Report.readCsv(report.csv());
        if (!existing.isEmpty() && !existing.get(0).keySet().equals(row.values.keySet())) {
            Run.Row aligned = new Run.Row();
            for (String k : existing.get(0).keySet()) aligned.put(k, row.values.getOrDefault(k, ""));
            aligned.problems.addAll(row.problems);
            aligned.topStatements.addAll(row.topStatements);
            row = aligned;
        }
        report.append(row);
    }
}
