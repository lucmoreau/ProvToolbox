    public StringBuilder addHeader(StringBuilder sb, String templateName, String packge, StackTraceElement stackTraceElement) {
        sb.insert(0, "# Generated by ProvToolbox for template configuration '" + templateName + "'\n"
                + "# by class " + stackTraceElement.getClassName() + ", method " + stackTraceElement.getMethodName() +
                ",\n# in file " + stackTraceElement.getFileName() + ", at line " + stackTraceElement.getLineNumber() + "\n\n");
        return sb;
    }

    public WritableObject toWritableObject(Class clazz, String className, String packge, StackTraceElement stackTraceElement) {
        this.currentPackageName = packge;
        this.currentClassName=className;
        StringBuilder theBuffer=emit(clazz);

        addHeader(theBuffer, className, packge, stackTraceElement);
        return new WritableObject() {
            @Override
            public void writeTo(File directory) throws IOException {
                Path destination = Paths.get(directory.getAbsolutePath()).resolve(packge.replace('.', '/'));
                destination.toFile().mkdirs();
                java.nio.file.Path path = destination.resolve(clazz.name + ".py");
                java.nio.file.Files.writeString(path, theBuffer.toString());
            }
        };
    }

    Set<String> imports;
    @Override
    public StringBuilder emit(Class clazz) {
        this.sb = new StringBuilder();
        return emit(clazz, sb);
    }

    public StringBuilder emit(Class clazz, StringBuilder sb) {
        this.currentClassSignature = (typeRegistry != null && currentPackageName != null)
                ? typeRegistry.lookup(clazz.name, currentPackageName) : null;

        imports = new java.util.HashSet<>();
        imports.add("past.util.Map");
        imports.add("past.util.List");

        // Class docstring from comments

        sb.append("\"\"\"");
        sb.append(clazz.comments.stream().map(this::convert).flatMap(Collection::stream).collect(Collectors.joining("\n")));
        sb.append("\"\"\"\n");


        // Class declaration
        sb.append("class ").append(sanitizeName(clazz.name));


        // Base classes (interfaces in Java become base classes in Python)
        // ignored for now
        sb.append(":\n");


        // Constructor (__init__)

        if (clazz.constructors.isEmpty()) {
            emitDefaultConstructor(clazz.fields);
        } else {
            for (Constructor constructor : clazz.constructors) {
                String constructorName="____init__"; // note the quadruple _ because the first two will be removed in sanitizeName, and we want to end up with __init__
                // "python:@OverloadedMethod" in annotations
                boolean overloaded=false;
                if (constructor.annotation != null) {
                    Optional<PythonAnnotation> annotation=constructor.annotation.stream()
                            .filter(annot -> annot instanceof PythonAnnotation)
                            .map(annot -> (PythonAnnotation) annot)
                            .filter(annot -> OverloadedMethod.NAME.equals(annot.getName()))
                            .findFirst()
                            ;
                    if (annotation.isPresent()) {
                        constructorName= ((OverloadedMethod) annotation.get()).getAltName();
                        overloaded=true;
                        //System.out.println("Constructor with @OverloadedMethod annotation, using alt name: " + constructorName);
                    }
                }
                Method pythonMethodAsConstructor = METHOD(constructorName)
                        .PARAMETERS(constructor.parameters)
                        .MODIFIERS(constructor.modifiers.toArray(new Modifier[0]))
                        .BODY(constructor.body.toArray(new Statement[0]))
                        //.ANNOTATIONS(constructor.annotation.toArray(new String[0]))
                        .COMMENTS(constructor.comments.toArray(new Comment[0]));

                for (Field field : clazz.fields) {
                    String fieldName = sanitizeName(field.name);
                    if (!field.modifiers.contains(Modifier.STATIC)) {
                        if (field.initialiser != null) {
                            pythonMethodAsConstructor.BODY(
                                    ASSIGNMENT(METHOD_CALL(VARIABLE("this"), fieldName), field.initialiser));

                        }
                    }
                }
                if (overloaded) {
                    pythonMethodAsConstructor.COMMENT("Note: this method was originally a PAST constructor, but was renamed to avoid name clashes due to overloading. \n It will not be recognized as a constructor by Python code, so it should be called explicitly by its name.");
                }
                emitMethod(pythonMethodAsConstructor);
            }
        }

        // Methods
        if (!clazz.methods.isEmpty()) {
            for (Method method : clazz.methods) {
                emitMethod(method);
            }
        }

        for (Method method: lateMethods) {
            emitMethod(method);
        }


        emitStaticFields(clazz.fields);


        if (!imports.isEmpty()) {
            sb.insert(0,"\n");
            sb.insert(0,"\n");
        }

        for (String imprt : imports) {
            // get suffix after last dot in imprt
            if (!imprt.contains(".")) continue;

            String suffix = getLocalName(imprt);
            // ignore LOGGER
            if (LOGGER.equals(suffix)) continue;
            if (imprt.startsWith(INTEGER.packge)) continue;
            //functools.singledispatch
            if (imprt.equals("functools.singledispatch")) {
                sb.insert(0, "from functools import singledispatch, update_wrapper\n");
            } else {
                sb.insert(0, "from " + imprt + " import " + suffix + "\n");
            }
        }

        if (!lateEmittedClasses.isEmpty()) {
            List<LateEmittedClass> tmp=lateEmittedClasses.stream().map(c -> c).collect(Collectors.toList());
            lateEmittedClasses.clear();
            sb.append("\n\n");

            for (Class lateClazz : tmp) {
                sb.append("# Late emitted class due to anonymous class\n");
                emit(lateClazz,sb);
                sb.append("\n\n");
            }
        }
        return sb;
    }

    List<Method> lateMethods=new java.util.ArrayList<>();
    private void lateEmitMethod(Method method) {
        this.lateMethods.add(method);
    }
    private String getLocalName(String imprt) {
        return switch (imprt) {
            case "past.lang.String" -> "str";
            case "past.lang.Integer" -> "int";
            case "past.lang.Float" -> "float";
            case "past.lang.Boolean" -> "bool";
            case "past.lang.Double" -> "float";
            default -> imprt.substring(imprt.lastIndexOf('.') + 1);
        };
    }
    private String importAndGetLocalName(String imprt) {
        imports.add(imprt);
        return getLocalName(imprt);
    }

    private String convert(TypeName tn) {
        switch (tn.typeKind) {
            case CLASS: {
                ClassName cn = (ClassName) tn;
                if (cn.packge!=null && !cn.packge.isEmpty()) {
                    return(cn.packge + "." + cn.simpleName);
                    //return cn.simpleName;
                } else {
                    return cn.simpleName;
                }
            }
            case VARIABLE:
            case ARRAY:
            case PARAMETERIZED:
            default: return (tn.toString());
        }

    }


    private String convertForInstanceCheck(TypeName tn) {
        switch (tn.typeKind) {
            case CLASS: {
                ClassName cn = (ClassName) tn;
                if (cn.packge != null && cn.packge.equals("past.lang")) {
                    // map past.lang types to python types
                    return switch (cn.simpleName) {
                        case "String" -> "str";
                        case "Integer", "int" -> "int";
                        case "Float" -> "float";
                        case "Boolean" -> "bool";
                        case "Object" -> "object";
                        default -> (cn.packge + "." + cn.simpleName);
                    };
                } else if (cn.packge != null && cn.packge.equals("org.openprovenance.prov.model")) {
                    return (cn.packge + "." + cn.simpleName);
                }
            }
            case VARIABLE:
            case ARRAY:
            case PARAMETERIZED:
            default: throw new IllegalArgumentException("Unsupported type for instanceof: " + tn);
        }
    }


    private List<String> convert(Comment c) {
        return List.of(String.format(c.format.replace("$L", "%s").replace("$N", "%s"), c.objects).split("\n"));
    }

