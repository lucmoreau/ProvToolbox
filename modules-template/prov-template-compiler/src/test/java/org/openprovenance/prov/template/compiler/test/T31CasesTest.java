    static final Pattern BUILD_DATE = Pattern.compile("buildDate = \"[^\"]*\"");
    static final Pattern TMP_CONV = Pattern.compile("tmp_Conv[0-9]+");

    Map<String, String> hashTree(File root, String id, Map<String, String> renaming) throws Exception {
        Map<String, String> res = new TreeMap<>();
        try (Stream<Path> s = Files.walk(root.toPath())) {
            for (Path p : s.filter(Files::isRegularFile).collect(Collectors.toList())) {
                String text = normalise(p, new String(Files.readAllBytes(p), StandardCharsets.UTF_8).replace("t31/" + id + "/", "t31/CASE/"));
                for (Map.Entry<String, String> r : renaming.entrySet()) text = text.replace(r.getKey(), r.getValue());
                MessageDigest md = MessageDigest.getInstance("SHA-256");
                res.put(root.toPath().relativize(p).toString(), new java.math.BigInteger(1, md.digest(text.getBytes(StandardCharsets.UTF_8))).toString(16));
            }
        }
        return res;
    }

    /** Neutralises what varies from one run to the next whatever the input (R14). */
    String normalise(Path p, String text) {
        text = BUILD_DATE.matcher(text).replaceAll("buildDate = \"<normalised>\"");
        text = TMP_CONV.matcher(text).replaceAll("tmp_Conv<n>");
        if (p.toString().endsWith(".json")) {
            try {
                text = sorted.writeValueAsString(sorted.treeToValue(sorted.readTree(text), Object.class));
            } catch (Exception e) {
                // not JSON after all: compared as text
            }
        }
        return text;
    }

    String diff(Map<String, String> a, Map<String, String> b, Set<String> ignored) {
        if (a == null || b == null) return "not generated";
        List<String> changed = new ArrayList<>(), added = new ArrayList<>(), removed = new ArrayList<>();
        for (String f : a.keySet()) {
            if (ignored.stream().anyMatch(f::contains)) continue;
            if (!b.containsKey(f)) removed.add(f); else if (!a.get(f).equals(b.get(f))) changed.add(f);
        }
        for (String f : b.keySet()) if (!a.containsKey(f) && ignored.stream().noneMatch(f::contains)) added.add(f);
        if (changed.isEmpty() && added.isEmpty() && removed.isEmpty()) return "identical";
        return "changed " + changed + (added.isEmpty() ? "" : ", added " + added) + (removed.isEmpty() ? "" : ", removed " + removed);
    }

    void inventory(File root) throws IOException {
        List<Path> files;
        try (Stream<Path> s = Files.walk(root.toPath())) {
            files = s.filter(Files::isRegularFile).sorted().collect(Collectors.toList());
        }
        for (String v : VARS) {
            String camel = Pattern.compile("_([a-z])").matcher(v).replaceAll(m -> m.group(1).toUpperCase());
            Pattern p = Pattern.compile("\\b(" + Pattern.quote(v) + "|" + Pattern.quote(camel) + ")\\b", Pattern.CASE_INSENSITIVE);
            List<String> hits = new ArrayList<>();
            for (Path f : files) {
                long n = p.matcher(Files.readString(f)).results().count();
                if (n > 0) hits.add(root.toPath().relativize(f) + " (" + n + ")");
            }
            report.append("- `").append(v).append("`: ").append(String.join(", ", hits)).append("\n");
        }
    }
