    void checkExpectations(String id, String from, JsonNode e) throws Exception {
        String where = from.equals(id) ? id : id + " (as " + from + ")";
        if (e.has("errorContains")) {
            String err = errors.get(id);
            check(where, "refused with \"" + e.get("errorContains").asText() + "\"",
                    err != null && err.contains("PrivacyException") && err.contains(e.get("errorContains").asText()));
            return;
        }
        if (!check(where, "generates", errors.get(id) == null)) return;
        String root = OUT + id + "/libs/";

        if (e.has("baseline")) {
            check(where, "no register", !new File(root + REGISTER).exists());
            check(where, "no privacy constraint", !read(root + SQL).contains("@pseudonym"));
        }
        if (e.has("noClientCheck")) check(where, "no client check", !read(root + BUILDER).contains("Pseudonyms"));
        if (e.has("sameAs")) {
            // R14: same files as the case named, but for the webjar's verbatim bindings copy and the register
            String d = diff(hashes.get(e.get("sameAs").asText()), hashes.get(id), Set.of("bindings/approval.json", "privacy-register"));
            check(where, "same output as " + e.get("sameAs").asText() + ": " + d, d.equals("identical"));
        }
        if (e.has("sameGeneratedAs")) {
            String other = e.get("sameGeneratedAs").asText();
            Map<String, String> renaming = new HashMap<>();
            if (e.has("renaming")) e.get("renaming").properties().forEach(m -> renaming.put(m.getKey(), m.getValue().asText()));
            String d = diff(hashes.get(other), renaming.isEmpty() ? hashes.get(id) : hashTree(new File(root), id, renaming),
                    Set.of("bindings/approval.json", "privacy-register"));
            check(where, "same generated code as " + other + ": " + d, d.equals("identical"));
        }
        if (e.has("newFiles")) {
            for (JsonNode f : e.get("newFiles")) check(where, "writes " + f.asText(), new File(root + WEBJAR + "html/" + f.asText()).exists());
        }
        if (e.has("absentFrom")) {
            for (Map.Entry<String, JsonNode> v : e.get("absentFrom").properties()) {
                for (JsonNode place : v.getValue()) check(where, v.getKey() + " absent from " + place.asText(), !inPlace(root, v.getKey(), place.asText()));
            }
        }
        if (e.has("keptIn")) {
            for (Map.Entry<String, JsonNode> v : e.get("keptIn").properties()) {
                for (JsonNode place : v.getValue()) check(where, v.getKey() + " kept in " + place.asText(), inPlace(root, v.getKey(), place.asText()));
            }
        }
        String sql = read(root + SQL);
        if (e.has("constraint")) {
            for (Map.Entry<String, JsonNode> v : e.get("constraint").properties()) {
                String col = v.getKey().equals("order") ? "_order" : v.getKey();
                check(where, "constraint on " + col + " for " + v.getValue().asText(),
                        sql.contains("ADD CONSTRAINT approval_" + col + "_p")
                                && Pattern.compile("COMMENT ON CONSTRAINT approval_" + Pattern.quote(col) + "_p[0-9a-f]{12} ON approval IS '"
                                + Pattern.quote(v.getValue().asText()) + " sha256:[0-9a-f]{64}'").matcher(sql).find());
            }
        }
        if (e.has("emptyColumn")) {   // D5
            for (Map.Entry<String, JsonNode> v : e.get("emptyColumn").properties()) {
                String col = v.getKey();
                check(where, col + " keeps its column", Pattern.compile("CREATE TABLE IF NOT EXISTS approval\\s*\\([^;]*\\b" + col + " TEXT").matcher(sql).find());
                check(where, col + " guarded by CHECK IS NULL", sql.contains("CHECK (" + col + " IS NULL) NOT VALID")
                        && Pattern.compile("COMMENT ON CONSTRAINT approval_" + col + "_t[0-9a-f]{12} ON approval IS '"
                        + Pattern.quote(v.getValue().asText()) + " sha256:").matcher(sql).find());
                check(where, col + " commented", sql.contains("COMMENT ON COLUMN approval." + col + " IS '@transient(" + v.getValue().asText() + ")"));
                check(where, "the old insert function dropped", sql.contains("DROP FUNCTION IF EXISTS insert_approval(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT);"));
            }
        }
        if (e.has("constraintPattern")) {
            for (Map.Entry<String, JsonNode> v : e.get("constraintPattern").properties()) {
                check(where, "inline check of " + v.getKey(), sql.contains(v.getKey() + " ~ '" + v.getValue().asText() + "'"));
            }
        }
        if (e.has("noSqlFunction")) check(where, "no SQL check function", !sql.contains("FUNCTION privacy"));
        if (e.has("privacyConstant")) {
            String builder = read(root + BUILDER);
            for (JsonNode p : e.get("privacyConstant")) {
                check(where, "privacy constant " + p.asText(), builder.contains("public static final String[] privacy")
                        && builder.contains("\"" + p.asText() + "@sha256:"));
            }
        }
        if (e.has("clientCheck")) {
            String java = read(root + BUILDER);
            String python = read(root + PY_BUILDER);
            for (Map.Entry<String, JsonNode> v : e.get("clientCheck").properties()) {
                String call = v.getValue().asText();
                String simple = call.substring(call.lastIndexOf('.', call.lastIndexOf('.') - 1) + 1);   // Class.method
                check(where, "Java client check " + simple + " on " + v.getKey() + ", in logX and args2bean",
                        count(java, simple + "(__" + v.getKey() + ",") == 2);
                check(where, "Python client check " + simple + " on " + v.getKey(), count(python, simple + "(" + v.getKey() + ",") == 2);
            }
        }
        if (e.has("schemaPattern")) {
            JsonNode schema = om.readTree(new File(root + SCHEMA));
            for (JsonNode v : e.get("schemaPattern")) {
                check(where, "schema pattern on " + v.asText(), schema.findValues(v.asText()).stream().anyMatch(n -> n.has("pattern")));
            }
        }
        List<JsonNode> register = new File(root + REGISTER).exists()
                ? listOf(om.readTree(new File(root + REGISTER))) : List.of();
        if (e.has("register")) {
            check(where, "register of " + e.get("register").asInt() + " rows, html too",
                    register.size() == e.get("register").asInt() && new File(root + REGISTER_HTML).exists());
        }
        checkRegisterField(where, e, register, "registerDefinedBy", "definedBy");
        checkRegisterField(where, e, register, "registerDecidedBy", "decidedBy");
        checkRegisterField(where, e, register, "registerDeclared", "declared");
        checkRegisterField(where, e, register, "registerNote", "note");
        if (e.has("digestDiffersFrom")) {
            String other = e.get("digestDiffersFrom").asText();
            List<JsonNode> theirs = listOf(om.readTree(new File(OUT + other + "/libs/" + REGISTER)));
            check(where, "digest of approver_ref differs from " + other,
                    !Objects.equals(row(register, "approver_ref").get("digest"), row(theirs, "approver_ref").get("digest")));
        }
        if (e.has("refused") || e.has("accepted")) {
            String variable = e.has("constraint") ? e.get("constraint").propertyNames().iterator().next() : "approver_ref";
            JsonNode r = row(register, variable);
            String pattern = r == null || r.get("pattern") == null ? null : r.get("pattern").asText();
            if (check(where, "a pattern for " + variable, pattern != null)) {
                for (JsonNode v : e.path("refused")) conform(where, pattern, v.isNull() ? null : v.asText(), false);
                for (JsonNode v : e.path("accepted")) conform(where, pattern, v.isNull() ? null : v.asText(), true);
            }
        }
        for (String k : List.of("union", "like")) {
            if (!e.has(k)) continue;
            List<String> others = new ArrayList<>();
            if (e.get(k).isArray()) e.get(k).forEach(n -> others.add(n.asText())); else others.add(e.get(k).asText());
            for (String o : others) {
                JsonNode theirs = byId.get(o).get("expect");
                ObjectNode copy = (ObjectNode) theirs.deepCopy();
                for (String drop : List.of("sameAs", "sameGeneratedAs", "register", "baseline", "noClientCheck", "digestDiffersFrom",
                        "registerDefinedBy", "registerDecidedBy", "registerDeclared", "registerNote", "constraintPattern", "privacyConstant")) {
                    copy.remove(drop);
                }
                if (k.equals("like")) { copy.remove("refused"); copy.remove("accepted"); }
                checkExpectations(id, o, copy);
            }
        }
    }

    /**
     * R15: the generated SQL in a real PostgreSQL, when {@code PROV_T31_PG_URL} names a database this test may wipe:
     * A6's valid record is accepted, each clear value refused by its constraint; P2's changed definition then replaces
     * the constraint (one constraint, new digest) without re-checking rows already written.
     */
    void liveDatabase(String pg) throws Exception {
        String where = "PostgreSQL";
        String hash = "k1:" + "0".repeat(64);
        psql(pg, "DROP SCHEMA public CASCADE; CREATE SCHEMA public;", null);
        // a legacy store: A0's SQL, and a past record with a clear name
        // (the test catalogue declares no sql.tables: the output table of 'approving' is created here)
        String a0 = "CREATE TABLE IF NOT EXISTS approving (ID SERIAL PRIMARY KEY);\n" + read(OUT + "A0/libs/" + SQL);
        check(where, "A0's SQL runs", psql(pg, null, a0).exitCode == 0);
        check(where, "A0 stores a past record with a name", psql(pg, "SELECT * FROM insert_approval('ex:agent/1', 'Jane Smith', "
                + "'hr:person/4711', 'ex:o0', NULL, NULL)", null).exitCode == 0);
        // the upgrade: A6's SQL on the legacy store (D5)
        check(where, "A6's SQL runs on the legacy store", psql(pg, null, read(OUT + "A6/libs/" + SQL)).exitCode == 0);
        check(where, "the past record keeps its value", psql(pg, "SELECT approver_name FROM approval WHERE _order = 'ex:o0'", null).output.trim().equals("Jane Smith"));
        check(where, "the old insert function is gone", psql(pg, "SELECT * FROM insert_approval('ex:agent/1', 'Jane Smith', "
                + "'hr:person/4711', 'ex:o0', NULL, NULL)", null).exitCode != 0);
        Psql bypass = psql(pg, "INSERT INTO approval(approving, approver_name) VALUES (99, 'Jane Smith')", null);
        check(where, "a writer bypassing the client is refused the name", bypass.exitCode != 0
                && bypass.output.contains("violates check constraint \"approval_approver_name_t"));
        check(where, "A6 accepts a valid record", psql(pg, "SELECT * FROM insert_approval('ex:agent/1', 'hr:person/4711', 'ex:o1', "
                + "'approved by ⟨person hr:person/4711⟩', '" + hash + "')", null).exitCode == 0);
        check(where, "its transient column is empty", psql(pg, "SELECT approver_name IS NULL FROM approval WHERE _order = 'ex:o1'", null).output.trim().equals("t"));
        for (String[] clear : List.of(new String[]{"approver_ref", "'Jane Smith', 'ex:o1', NULL, NULL"},
                new String[]{"order_note", "'hr:person/1', 'ex:o1', 'see ⟨person Jane Smith⟩', NULL"},
                new String[]{"customer_hash", "'hr:person/1', 'ex:o1', NULL, 'ACME Ltd'"})) {
            Psql r = psql(pg, "SELECT * FROM insert_approval('ex:agent/1', " + clear[1] + ")", null);
            check(where, "A6 refuses a clear " + clear[0], r.exitCode != 0 && r.output.contains("violates check constraint \"approval_" + clear[0] + "_p"));
        }
        check(where, "P2's SQL runs", psql(pg, null, read(OUT + "P2/libs/" + SQL)).exitCode == 0);
        Psql constraints = psql(pg, "SELECT obj_description(oid, 'pg_constraint') FROM pg_constraint WHERE conname LIKE 'approval\\_approver\\_ref\\_p%'", null);
        String p2digest = row(listOf(om.readTree(new File(OUT + "P2/libs/" + REGISTER))), "approver_ref").get("digest").asText();
        check(where, "P2 replaces approver_ref's constraint: " + constraints.output.trim(),
                constraints.output.trim().equals("pt:erp-ref sha256:" + p2digest));
        check(where, "P2 refuses smith:john", psql(pg, "SELECT * FROM insert_approval('ex:agent/1', 'smith:john', 'ex:o1', NULL, NULL)", null).exitCode != 0);
    }

    static final class Psql {
        final int exitCode;
        final String output;

        Psql(int exitCode, String output) {
            this.exitCode = exitCode;
            this.output = output;
        }
    }

    static Psql psql(String pg, String command, String script) throws Exception {
        List<String> cmd = new ArrayList<>(List.of("psql", "-X", "-q", "-tA", "-v", "ON_ERROR_STOP=1", pg));
        if (command != null) cmd.addAll(List.of("-c", command));
        Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
        if (script != null) p.getOutputStream().write(script.getBytes(StandardCharsets.UTF_8));
        p.getOutputStream().close();
        String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        return new Psql(p.waitFor(), out);
    }

    /** Where a variable's value goes, in the generated files of one case. */
    boolean inPlace(String root, String var, String place) throws IOException {
        String col = var.equals("order") ? "_order" : var;
        switch (place) {
            case "store":   // written to the store (D5: a transient column stays in the table, never written)
                return Pattern.compile("INSERT INTO approval\\([^)]*\\b" + col + "\\b").matcher(read(root + SQL)).find()
                        || read(root + SQL).contains("input_" + col + " ")
                        || read(root + INVOKER).contains("bean." + var + ")")
                        || read(root + BUILDER).contains(", " + col + ",") || read(root + BUILDER).contains(", " + col + ")");
            case "log": {
                String b = read(root + BUILDER);
                return b.contains("sb.append(__" + var + ")") || b.contains("escapeCsv(__" + var + ")");
            }
            case "expansion": {
                String l2p = read(root + L2P_BUILDER);
                return Pattern.compile("__C_document=generator\\([^;]*\\b" + var + "\\b").matcher(l2p).find();
            }
            case "bean":
                return read(root + BEAN).contains(" " + var + ";");
            case "schema":
                return om.readTree(new File(root + SCHEMA)).findValues(var).size() > 0;
            case "doc":
                return read(root + DOC).contains(">" + var + "<");
            default:
                throw new IllegalArgumentException("unknown place " + place);
        }
    }

    /** R16: the Java runtime, the Python port and JavaScript's RegExp give the same answer; PostgreSQL when configured. */
    void conform(String where, String pattern, String value, boolean expected) throws Exception {
        String shown = value == null ? "null" : "\"" + value + "\"";
        check(where, "Java " + (expected ? "accepts " : "refuses ") + shown, Pseudonyms.matches(value, pattern) == expected);
        if (value == null) return;
        Boolean py = external("python3", List.of("-I", "-c",
                "import sys; sys.path.insert(0, sys.argv[1]);"
                        + "from org.openprovenance.prov.template.privacy.Pseudonyms import Pseudonyms;"
                        + "print(Pseudonyms.matches(sys.argv[3], sys.argv[2]))",
                new File("../prov-template-library/src/main/python").getAbsolutePath(), pattern, value));
        if (py != null) check(where, "Python " + (expected ? "accepts " : "refuses ") + shown, py == expected);
        Boolean js = external("node", List.of("-e",
                "console.log(new RegExp(process.argv[1], 'u').test(process.argv[2]) ? 'True' : 'False')", pattern, value));
        if (js != null) check(where, "JavaScript " + (expected ? "accepts " : "refuses ") + shown, js == expected);
        String pg = System.getenv("PROV_T31_PG_URL");
        if (pg != null) {
            Boolean p = external("psql", List.of(pg, "-tAc", "SELECT CASE WHEN " + sqlLiteral(value) + " ~ " + sqlLiteral(pattern)
                    + " THEN 'True' ELSE 'False' END"));
            if (p != null) check(where, "PostgreSQL " + (expected ? "accepts " : "refuses ") + shown, p == expected);
        }
    }

    static final Map<String, Boolean> available = new HashMap<>();

    /** Runs a command printing True or False; null when the command isn't available here. */
    static Boolean external(String command, List<String> args) throws Exception {
        if (Boolean.FALSE.equals(available.get(command))) return null;
        List<String> cmd = new ArrayList<>();
        cmd.add(command);
        cmd.addAll(args);
        try {
            Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
            String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8).trim();
            p.waitFor();
            available.put(command, true);
            if (out.endsWith("True")) return true;
            if (out.endsWith("False")) return false;
            throw new IllegalStateException(command + " said: " + out);
        } catch (IOException notInstalled) {
            available.put(command, false);
            return null;
        }
    }

    void checkRegisterField(String where, JsonNode e, List<JsonNode> register, String key, String field) {
        if (!e.has(key)) return;
        for (Map.Entry<String, JsonNode> v : e.get(key).properties()) {
            JsonNode r = row(register, v.getKey());
            String actual = r == null || r.get(field) == null || r.get(field).isNull() ? null : r.get(field).asText();
            String wanted = v.getValue().isNull() ? null : v.getValue().asText();
            check(where, "register " + field + " of " + v.getKey() + " is " + wanted, r != null && Objects.equals(wanted, actual));
        }
    }

    static JsonNode row(List<JsonNode> register, String variable) {
        return register.stream().filter(r -> variable.equals(r.get("variable").asText())).findFirst().orElse(null);
    }

    static List<JsonNode> listOf(JsonNode array) {
        List<JsonNode> res = new ArrayList<>();
        array.forEach(res::add);
        return res;
    }

    boolean check(String where, String what, boolean ok) {
        if (!ok) failures.add("- " + where + ": " + what);
        return ok;
    }

    static int count(String text, String s) {
        int n = 0;
        for (int i = text.indexOf(s); i >= 0; i = text.indexOf(s, i + 1)) n++;
        return n;
    }

    static String read(String path) throws IOException {
        File f = new File(path);
        return f.exists() ? Files.readString(f.toPath()) : "";
    }

    static String sqlLiteral(String s) {
        return "'" + s.replace("'", "''") + "'";
    }

