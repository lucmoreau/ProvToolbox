    public void testCases() throws Exception {
        JsonNode cases = om.readTree(new File(RES + "cases.json")).get("cases");
        for (JsonNode c : cases) byId.put(c.get("id").asText(), c);

        FileUtils.deleteDirectory(new File(OUT));
        report.append("# T31: the test configurations, generated\n\n");

        for (JsonNode c : cases) {
            String id = c.get("id").asText();
            hashes.put(id, runCase(id, c));
        }
        hashes.put("A0bis", runCase("A0bis", byId.get("A0")));   // determinism

        report.append("\n## Differences from A0\n\n");
        Map<String, String> a0 = hashes.get("A0");
        for (Map.Entry<String, Map<String, String>> e : hashes.entrySet()) {
            if (e.getKey().equals("A0") || e.getValue() == null) continue;
            report.append("- **").append(e.getKey()).append("**: ").append(diff(a0, e.getValue(), Set.of())).append("\n");
        }
        report.append("\n## Where each variable of A0 lands\n\n");
        inventory(new File(OUT + "A0/libs"));

        check("A0bis", "generation is deterministic", "identical".equals(diff(a0, hashes.get("A0bis"), Set.of())));
        for (JsonNode c : cases) {
            String id = c.get("id").asText();
            checkExpectations(id, id, c.get("expect"));
        }

        String pg = System.getenv("PROV_T31_PG_URL");
        if (pg != null) liveDatabase(pg);

        report.append("\n## Failed expectations\n\n").append(failures.isEmpty() ? "none\n" : String.join("\n", failures) + "\n");
        Files.writeString(Path.of(OUT + "cases.md"), report.toString());
        System.out.println(report);
        assertTrue("T31 expectations failed:\n" + String.join("\n", failures), failures.isEmpty());
    }

